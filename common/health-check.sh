#!/usr/bin/env bash

set -euo pipefail
source ./health.conf

echo "======================================================"
echo "==================SYSTEM STATUS===================="
echo -e "======================================================\n"
echo "Hostname: $(hostname)"
echo "kernal version: $(hostnamectl | grep Kernel | cut -d":" -f2)"
echo "Current Date: $(date)"
echo "Uptime: $(uptime | cut -d"," -f1,2)"
echo "Number of runnig processes: $(ps -e --no-headers | wc -l)"

echo "======================================================"
echo "==================SYSTEM RESOURCES===================="
echo -e "======================================================\n"
echo "Load average: $(uptime | cut -d"," -f3)"
echo "CPU usage:"
echo "--------------------------------------------------------------"
sar -u 1 7
echo -e "--------------------------------------------------------------\n"
echo "Memory usage:"
echo "--------------------------------------------------------------"
free -h | awk 'NR <= 2'
echo -e "--------------------------------------------------------------\n"
echo "Swap usage:"
echo "--------------------------------------------------------------"
free -h | awk 'NR==1 || NR==3'
echo -e "--------------------------------------------------------------\n"
echo "Disk usage: $(df -h / | awk 'NR==2 {print $5}' | tr -d "%")%"
echo "--------------------------------------------------------------"
df -h
echo -e "--------------------------------------------------------------\n"
echo "Inode usage:"
echo "--------------------------------------------------------------"
df -hi
echo -e "--------------------------------------------------------------\n"
echo "Disk I/O:"
echo "--------------------------------------------------------------"
iostat -dh
echo -e "--------------------------------------------------------------\n"

echo "======================================================"
echo "==================SERVICES AND PROCESSES===================="
echo -e "======================================================\n"
echo "Critical services status:"
echo "--------------------------------------------------------------"
for service in "${services[@]}"; do
    echo "=== $service ==="
    sudo systemctl is-active "$service"
    sudo systemctl is-enabled "$service"
    echo
done
echo -e "--------------------------------------------------------------\n"
echo "Zombie processes:"
echo "--------------------------------------------------------------"
ps aux | awk '$8=="Z" || $8=="Z+"'
echo -e "--------------------------------------------------------------\n"
echo "Top 5 CPU consuming processes:"
echo "--------------------------------------------------------------"
ps -eo pid,user,%cpu,%mem,cmd --sort=-%cpu | head -n 6
echo -e "--------------------------------------------------------------\n"

echo "======================================================"
echo "==================NETWORK AND REACHABILITY===================="
echo -e "======================================================\n"
echo "Interfaces:"
echo "--------------------------------------------------------------"
ip -br link show
echo -e "--------------------------------------------------------------\n"
echo "IP addresses:"
echo "--------------------------------------------------------------"
ip -br addr show
echo -e "--------------------------------------------------------------\n"
echo "The listeing ports:"
echo "--------------------------------------------------------------"
sudo ss -ltun
echo -e "--------------------------------------------------------------\n"
echo "Firewall ruleset:"
echo "--------------------------------------------------------------"
sudo nft list ruleset | grep -q .
echo -e "--------------------------------------------------------------\n"

# runnig server specific health check
./health-extra.sh

echo "======================================================"
echo "==================LOGS AND ERORRS===================="
echo -e "======================================================\n"

echo "recent errors."
echo "--------------------------------------------------------------"
sudo jornalctl -p err | head -n 15
echo -e "--------------------------------------------------------------\n"
